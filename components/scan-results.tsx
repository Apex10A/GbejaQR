export function ScanResults() {
  const [visible, setVisible] = useState(false)
  const ref = useRef<HTMLDivElement>(null)

  useEffect(() => {
    const observer = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) setVisible(true)
      },
      { threshold: 0.1 }
    )
    if (ref.current) observer.observe(ref.current)
    return () => observer.disconnect()
  }, [])

  return (
    <section id="scan-results" ref={ref} className="relative py-24 lg:py-32">
      <div className="mx-auto max-w-7xl px-4 lg:px-8">
        <div className="mx-auto mb-16 max-w-2xl text-center">
          <span className="     mb-4 inline-block text-xs font-medium uppercase tracking-widest text-primary font-mono">
            What You See
          </span>
          <h2 className="mb-4 text-3xl font-bold tracking-tight text-foreground lg:text-4xl font-sans text-balance">
            Clear security verdicts you can trust
          </h2>
          <p className="text-muted-foreground leading-relaxed">
            Every scan produces a color-coded result with a plain-language explanation. No jargon. No guesswork.
          </p>
        </div>

        <div className="grid gap-6 sm:grid-cols-2 xl:grid-cols-4">
          <VerifiedCard visible={visible} delay={0} />
          <SuspiciousCard visible={visible} delay={150} />
          <MaliciousCard visible={visible} delay={300} />
          <SafetyTipsCard visible={visible} delay={450} />
        </div>
      </div>
    </section>
  )
}
